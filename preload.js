const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('api', {
  start: (cfg) => ipcRenderer.invoke('start', cfg),
  startFast: (cfg) => ipcRenderer.invoke('start-fast', cfg),
  loadIds: (cfg) => ipcRenderer.invoke('load-ids', cfg),
  hunt: (cfg) => ipcRenderer.invoke('hunt', cfg),
  tuneHunt: (cfg) => ipcRenderer.send('hunt-tune', cfg),
  stopHunt: () => ipcRenderer.send('hunt-stop'),
  accList: () => ipcRenderer.invoke('acc-list'),
  accAdd: (text) => ipcRenderer.invoke('acc-add', text),
  accRemove: (logins) => ipcRenderer.invoke('acc-remove', logins),
  accUse: (logins, use) => ipcRenderer.invoke('acc-use', { logins, use }),
  accRefresh: () => ipcRenderer.invoke('acc-refresh', {}),
  accClear: (a) => ipcRenderer.invoke('acc-clear', a),
  accReveal: (login) => ipcRenderer.invoke('acc-reveal', login),
  accImportFile: (password) => ipcRenderer.invoke('acc-import-file', password),
  accExport: (password) => ipcRenderer.invoke('acc-export', password),
  accImport: (text, password) => ipcRenderer.invoke('acc-import', { text, password }),
  openFile: (key) => ipcRenderer.invoke('open-file', key),
  countIds: () => ipcRenderer.invoke('ids-count'),
  accAddFile: () => ipcRenderer.invoke('acc-add-file'),
  openLink: (key) => ipcRenderer.invoke('open-link', key),
  updateCheck: () => ipcRenderer.invoke('update-check'),
  appInfo: () => ipcRenderer.invoke('app-info'),
  openDir: () => ipcRenderer.invoke('files-open'),
  onProgress: (f) => ipcRenderer.on('progress', (_e, st) => f(st)),
  sendCode: (code) => ipcRenderer.send('code', code),
  cancelCode: () => ipcRenderer.send('code-cancel'),
  accCopy: (login, what) => ipcRenderer.invoke('acc-copy', { login, what }),
  onLog: (f) => ipcRenderer.on('log', (_e, key, p) => f(key, p)),
  onAskCode: (f) => ipcRenderer.on('ask-code', (_e, n, domain, wrong) => f(n, domain, wrong)),
});
